"""خدمة توليد المواقع — تصميمات احترافية"""
import os
import re
from django.conf import settings
from .fallback_designs import (
    saas_design, agency_design, portfolio_design, restaurant_design,
)


SYSTEM_PROMPT = """أنت مطور ويب senior بخبرة 10 سنوات. تكتب كود HTML/CSS نظيف بأسلوب مبرمجين محترفين.

قواعد صارمة:
1. لا تكتب أي إشارة للذكاء الاصطناعي ("AI", "Generated by", "Created with")
2. استخدم تعليقات HTML بأسلوب مبرمج حقيقي (<!-- Hero Section -->)
3. ألوان احترافية متوازنة — لا تدرجات صارخة
4. خطوط احترافية (Tajawal / Inter / Playfair Display)
5. spacing مدروس (py-16, gap-8)
6. أسماء classes بأسلوب مبرمج (hero, nav, cta, feature-grid)
7. تصميم بأسلوب Stripe / Linear / Vercel — بسيط وأنيق
8. بدون emoji في الكود
9. RTL للعربية + خط Tajawal
10. الكود يبدو كأنه مكتوب يدوياً من مبرمج محترف"""


def _clean_code(code):
    """تنظيف الكود من إشارات AI"""
    patterns = [
        r'<!--\s*Generated by.*?-->',
        r'<!--\s*AI.*?-->',
        r'<!--\s*Created with.*?-->',
        r'Powered by\s+AI',
        r'AI[\s-]?generated',
        r'built with\s+AI',
        r'Made with\s+AI',
    ]
    for p in patterns:
        code = re.sub(p, '', code, flags=re.IGNORECASE)

    code = re.sub(r'^```html\s*', '', code)
    code = re.sub(r'^```\s*', '', code)
    code = re.sub(r'```\s*$', '', code)

    return code.strip()


def generate_website_code(user_prompt, template_key=None):
    """توليد كود HTML/CSS احترافي"""
    api_key = getattr(settings, 'GEMINI_API_KEY', '') or os.environ.get('GEMINI_API_KEY', '')

    if not api_key:
        return _fallback(user_prompt, template_key)

    try:
        import google.generativeai as genai
        genai.configure(api_key=api_key)
        model = genai.GenerativeModel('gemini-1.5-flash')

        full_prompt = f"""{SYSTEM_PROMPT}

المطلوب: موقع احترافي بناءً على:
"{user_prompt}"

المتطلبات:
- HTML5 + Tailwind CSS (CDN)
- خط Tajawal
- RTL
- Responsive
- بدون مكتبات JS ثقيلة
- يبدو كمبرمج senior

أخرج الكود فقط، ابدأ بـ <!DOCTYPE html>"""

        response = model.generate_content(full_prompt)
        code = _clean_code(response.text)
        return code, None
    except Exception as e:
        return _fallback(user_prompt, template_key)


def _fallback(prompt, template_key=None):
    """استخدام تصميم احتياطي"""
    designs = {
        'saas': saas_design,
        'agency': agency_design,
        'portfolio': portfolio_design,
        'restaurant': restaurant_design,
    }

    if template_key and template_key in designs:
        return designs[template_key](prompt), None

    # افتراضي
    return saas_design(prompt), None
